create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null,
    role text not null check (role in ('artisan', 'buyer')),
    craft_specialty text,
    location text,
    created_at timestamptz not null default now()
);

-- Add profile fields when upgrading an older profiles table.
alter table public.profiles add column if not exists full_name text;
alter table public.profiles add column if not exists role text;
alter table public.profiles add column if not exists craft_specialty text;
alter table public.profiles add column if not exists location text;
alter table public.profiles add column if not exists profile_image_url text;
alter table public.profiles add column if not exists story text;
alter table public.profiles add column if not exists created_at timestamptz default now();

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    artisan_id uuid not null references public.profiles(id) on delete cascade,
    title text not null,
    category text not null,
    price numeric not null check (price >= 0),
    image_url text,
    image_urls jsonb not null default '[]'::jsonb,
    description text,
    created_at timestamptz not null default now()
);

alter table public.products add column if not exists image_urls jsonb not null default '[]'::jsonb;

create table if not exists public.wishlists (
    id bigint generated by default as identity primary key,
    buyer_id uuid not null references public.profiles(id) on delete cascade,
    product_id bigint not null references public.products(id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (buyer_id, product_id)
);

create table if not exists public.cart_items (
    id bigint generated by default as identity primary key,
    buyer_id uuid not null references public.profiles(id) on delete cascade,
    product_id bigint not null references public.products(id) on delete cascade,
    quantity integer not null default 1 check (quantity > 0),
    created_at timestamptz not null default now(),
    unique (buyer_id, product_id)
);

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    buyer_id uuid not null references public.profiles(id) on delete cascade,
    product_id bigint not null references public.products(id) on delete cascade,
    quantity integer not null default 1 check (quantity > 0),
    total_price numeric not null check (total_price >= 0),
    status text not null default 'pending' check (status in ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
    created_at timestamptz not null default now()
);

create table if not exists public.product_reviews (
    id bigint generated by default as identity primary key,
    buyer_id uuid not null references public.profiles(id) on delete cascade,
    product_id bigint not null references public.products(id) on delete cascade,
    rating integer not null check (rating between 1 and 5),
    review text not null,
    created_at timestamptz not null default now(),
    unique (buyer_id, product_id)
);

