drop policy if exists "Artisans can publish products" on public.products;
create policy "Artisans can publish products"
    on public.products for insert
    with check (
        auth.uid() = artisan_id
        and exists (
            select 1 from public.profiles
            where id = auth.uid() and role = 'artisan'
        )
    );

