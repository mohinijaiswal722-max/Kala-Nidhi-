create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
    insert into public.profiles (id, full_name, role, craft_specialty, location, profile_image_url, story)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        coalesce(new.raw_user_meta_data ->> 'role', 'buyer'),
        new.raw_user_meta_data ->> 'specialty',
        new.raw_user_meta_data ->> 'location',
        new.raw_user_meta_data ->> 'profile_image_url',
        new.raw_user_meta_data ->> 'story'
    )
    on conflict (id) do update set
        full_name = excluded.full_name,
        role = excluded.role,
        craft_specialty = excluded.craft_specialty,
        location = excluded.location,
        profile_image_url = excluded.profile_image_url,
        story = excluded.story;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute procedure public.handle_new_user();

-- Backfill profiles for Auth users created before this trigger existed.
insert into public.profiles (id, full_name, role, craft_specialty, location, profile_image_url, story)
select
    id,
    coalesce(raw_user_meta_data ->> 'full_name', ''),
    case when raw_user_meta_data ->> 'role' = 'artisan' then 'artisan' else 'buyer' end,
    raw_user_meta_data ->> 'specialty',
    raw_user_meta_data ->> 'location',
    raw_user_meta_data ->> 'profile_image_url',
    raw_user_meta_data ->> 'story'
from auth.users
on conflict (id) do update set
    full_name = excluded.full_name,
    role = excluded.role,
    craft_specialty = excluded.craft_specialty,
    location = excluded.location,
    profile_image_url = excluded.profile_image_url,
    story = excluded.story;

